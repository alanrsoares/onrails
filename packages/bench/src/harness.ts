import { mkdir } from "node:fs/promises";
import path from "node:path";
import { do_not_optimize } from "mitata";

/** Sink so JIT cannot erase the measured work. */
export const blackbox = do_not_optimize;

export type CliFlags = {
  readonly ci: boolean;
  readonly markdown: boolean;
  readonly runtime: boolean;
  readonly bundle: boolean;
};

export const parseFlags = (argv: readonly string[]): CliFlags => {
  const runtimeOnly = argv.includes("--runtime");
  const bundleOnly = argv.includes("--bundle");
  const all = !runtimeOnly && !bundleOnly;
  return {
    ci: argv.includes("--ci"),
    markdown: argv.includes("--markdown"),
    runtime: all || runtimeOnly,
    bundle: all || bundleOnly,
  };
};

export type BenchMeta = {
  readonly bunVersion: string;
  readonly platform: string;
  readonly arch: string;
  readonly date: string;
  readonly deps: Readonly<Record<string, string>>;
};

const readPkgVersion = async (specifier: string): Promise<string> => {
  const pkgPath = Bun.resolveSync(`${specifier}/package.json`, import.meta.dir);
  const pkg = (await Bun.file(pkgPath).json()) as { version?: string };
  return pkg.version ?? "unknown";
};

export const collectMeta = async (): Promise<BenchMeta> => ({
  bunVersion: Bun.version,
  platform: process.platform,
  arch: process.arch,
  date: new Date().toISOString(),
  deps: {
    "@onrails/result": await readPkgVersion("@onrails/result"),
    "@onrails/pattern": await readPkgVersion("@onrails/pattern"),
    neverthrow: await readPkgVersion("neverthrow"),
    "ts-pattern": await readPkgVersion("ts-pattern"),
    mitata: await readPkgVersion("mitata"),
  },
});

export const resultsDir = path.join(import.meta.dir, "..", "results");
export const resultsMdPath = path.join(import.meta.dir, "..", "RESULTS.md");

export const writeJson = async (name: string, data: unknown): Promise<string> => {
  await mkdir(resultsDir, { recursive: true });
  const out = path.join(resultsDir, name);
  await Bun.write(out, `${JSON.stringify(data, null, 2)}\n`);
  return out;
};

export type RuntimeRow = {
  readonly name: string;
  readonly avgNs: number | null;
  readonly error: string | null;
};

export const flattenRuntimeRows = (benchmarks: readonly unknown[]): RuntimeRow[] => {
  const rows: RuntimeRow[] = [];
  for (const raw of benchmarks) {
    const b = raw as {
      runs?: readonly {
        name?: string;
        stats?: { avg?: number };
        error?: unknown;
      }[];
    };
    for (const run of b.runs ?? []) {
      rows.push({
        name: run.name ?? "(unnamed)",
        avgNs: typeof run.stats?.avg === "number" ? run.stats.avg : null,
        error: run.error != null ? String(run.error) : null,
      });
    }
  }
  return rows;
};

const fmtNs = (ns: number | null): string => {
  if (ns == null) return "—";
  if (ns < 1e3) return `${ns.toFixed(2)} ns`;
  if (ns < 1e6) return `${(ns / 1e3).toFixed(2)} µs`;
  return `${(ns / 1e6).toFixed(2)} ms`;
};

export type BundleRow = {
  readonly id: string;
  readonly minifyBytes: number;
  readonly gzipBytes: number;
};

export const renderResultsMarkdown = (
  meta: BenchMeta,
  runtime: readonly RuntimeRow[],
  bundles: readonly BundleRow[],
): string => {
  const depLines = Object.entries(meta.deps)
    .map(([k, v]) => `- \`${k}\`@${v}`)
    .join("\n");

  const runtimeTable = [
    "| benchmark | avg |",
    "|---|---:|",
    ...runtime.map((r) => `| \`${r.name}\` | ${r.error ? `error: ${r.error}` : fmtNs(r.avgNs)} |`),
  ].join("\n");

  const bundleTable = [
    "| import graph | minify | minify+gzip |",
    "|---|---:|---:|",
    ...bundles.map(
      (b) =>
        `| \`${b.id}\` | ${b.minifyBytes.toLocaleString()} B | ${b.gzipBytes.toLocaleString()} B |`,
    ),
  ].join("\n");

  return `# Benchmark results

> Snapshot regenerated by \`bun run bench:md\`. Microbenchmarks ≠ app perf.
> Pattern compares only the overlapping shallow surface (no \`P.select\` / deep wildcards).

## Environment

- date: ${meta.date}
- bun: ${meta.bunVersion}
- platform: ${meta.platform}/${meta.arch}

### Versions

${depLines}

## Runtime (avg)

${runtimeTable}

## Bundle (fair import graphs)

Headline metric is **minify+gzip**. These are sizes of the listed import graphs, not whole-package weight.

${bundleTable}
`;
};
